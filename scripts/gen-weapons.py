#!/usr/bin/env python3
"""Generate src/content/weapons.ts from the Rust port's decoded TS 3.0 weapon table.

Usage:
  python3 -I scripts/gen-weapons.py path/to/the-specialistsmod-rs/crates/shared/data/weapons.toml
"""

import sys
import tomllib
from pathlib import Path

ATT = [(1, "silencer"), (2, "laser"), (4, "flashlight"), (8, "scope")]
KIND = {
    "pistol": "Pistol", "smg": "SMG", "rifle": "Rifle", "shotgun": "Shotgun", "sniper": "Sniper",
    "akimbo": "Akimbo", "akimbo_only": "Akimbo", "grenade": "Grenade", "knife": "Blade", "katana": "Blade",
}
MODE = {"auto": "auto", "semi": "semi", "burst": "burst", "pump": "pump", "ak_semi": "akimbo-semi", "ak_auto": "akimbo-auto"}
# Blast damage for the grenade (combat.toml), which the weapon table lists as 0.
GRENADE_DAMAGE = 110


def s(x):
    return "'" + x.replace("'", "\\'") + "'"


def arr(xs):
    return "[" + ", ".join(s(x) for x in xs) + "]"


def num(x):
    return str(int(x)) if x == int(x) else repr(round(x, 4))


def main():
    table = tomllib.loads(Path(sys.argv[1]).read_text())["weapon"]
    out = Path(__file__).resolve().parent.parent / "src/content/weapons.ts"
    lines = [
        "// TS 3.0 weapon stats, generated by scripts/gen-weapons.py from the Rust port's decoded",
        "// tables (the-specialistsmod-rs crates/shared/data/weapons.toml, from ts_i386.so).",
        "// Kung fu (weapon 0) is left out. Damage is per bullet; shotguns fire `pellets` per shot.",
        "// Pellet guns are listed as shotguns (TS files the USAS-12 and Sawed-off by HUD category),",
        "// the grenade's damage is its blast, and akimbo-only pairs are flagged.",
        "",
        "export type FireMode = 'auto' | 'semi' | 'burst' | 'pump' | 'akimbo-semi' | 'akimbo-auto'",
        "export type Attachment = 'silencer' | 'laser' | 'flashlight' | 'scope'",
        "",
        "export type Weapon = {",
        "  id: number",
        "  name: string",
        "  kind: 'Pistol' | 'SMG' | 'Rifle' | 'Shotgun' | 'Sniper' | 'Akimbo' | 'Grenade' | 'Blade'",
        "  slots: number",
        "  cost: number",
        "  clip: number | null",
        "  damage: number",
        "  pellets: number | null",
        "  /** Seconds between shots (or swings). */",
        "  rate: number",
        "  reload: number",
        "  /** Gun-butt strike damage on the alternate attack key, 0 if none. */",
        "  stock: number",
        "  modes: FireMode[]",
        "  /** Attachments you can add. */",
        "  attachments: Attachment[]",
        "  /** Attachments the weapon always has. */",
        "  builtIn: Attachment[]",
        "  /** Id of this gun's akimbo pair, bought by taking the gun twice. */",
        "  pairId: number | null",
        "  /** For an akimbo pair: the single gun it is made of (two of them). */",
        "  singleId: number | null",
        "  /** Only sold as a pair. */",
        "  akimboOnly: boolean",
        "  /** Bought by count; each one takes `slots`. */",
        "  stack: boolean",
        "}",
        "",
        "export const weapons: Weapon[] = [",
    ]
    for w in table:
        if w["kind"] == "kungfu":
            continue
        melee = w["kind"] in ("grenade", "knife", "katana")
        kind = KIND[w["kind"]]
        if w["pellets"] > 1 and not melee:
            kind = "Shotgun"
        damage = GRENADE_DAMAGE if w["kind"] == "grenade" else w["damage"]
        modes = [] if melee else [MODE[m] for m in w["modes"]]
        att = [n for b, n in ATT if w["att_allowed"] & b and not w["att_default"] & b]
        built = [n for b, n in ATT if w["att_default"] & b]
        fields = [
            f"id: {w['id']}",
            f"name: {s(w['name'])}",
            f"kind: {s(kind)}",
            f"slots: {w['slots']}",
            f"cost: {w['cost']}",
            f"clip: {'null' if melee else w['clip']}",
            f"damage: {num(damage)}",
            f"pellets: {w['pellets'] if w['pellets'] > 1 and not melee else 'null'}",
            f"rate: {num(w['rate'])}",
            f"reload: {num(w['reload'])}",
            f"stock: {w['stock']}",
            f"modes: {arr(modes)}",
            f"attachments: {arr(att)}",
            f"builtIn: {arr(built)}",
            f"pairId: {w['akimbo'] if w['akimbo'] >= 0 else 'null'}",
            f"singleId: {w['single'] if w['kind'] == 'akimbo' and w['single'] >= 0 else 'null'}",
            f"akimboOnly: {'true' if w['kind'] == 'akimbo_only' else 'false'}",
            f"stack: {'true' if w['stack'] else 'false'}",
        ]
        lines.append("  { " + ", ".join(fields) + " },")
    lines += [
        "]",
        "",
        "export const weaponById = new Map(weapons.map((w) => [w.id, w]))",
        "",
        "export const attachmentPrices: Record<Attachment, number> = { silencer: 900, laser: 800, flashlight: 500, scope: 1800 }",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
