#!/usr/bin/env python3
"""Generate the Manual's weapon tables from the Rust port's decoded weapon tables.

Usage:
  python3 -I scripts/gen-weapons.py <the-specialistsmod-rs>/crates/shared/data/weapons.toml
      writes src/content/weapons.ts (TS 3.0)
  python3 -I scripts/gen-weapons.py --ts21 <the-specialistsmod-rs>/crates/ts21/data/weapons21.toml \
      <the-specialistsmod-rs>/crates/ts21/data/ammo21.toml
      writes src/content/weapons21.ts (TS 2.1)

TS 2.1's table stores a damage multiplier (`mult`) instead of the damage: a bullet does its ammo
type's base damage (ammo21.toml `damage`) times the multiplier. Its `stock` is a flag; the stock
hit always does 20.
"""

import sys
import tomllib
from pathlib import Path

ATT = [(1, "silencer"), (2, "laser"), (4, "flashlight"), (8, "scope")]
KIND = {
    "pistol": "Pistol", "smg": "SMG", "rifle": "Rifle", "shotgun": "Shotgun", "sniper": "Sniper",
    "akimbo": "Akimbo", "akimbo_only": "Akimbo", "grenade": "Grenade", "knife": "Blade", "katana": "Blade",
}
MODE = {"auto": "auto", "semi": "semi", "burst": "burst", "pump": "pump", "ak_semi": "akimbo-semi", "ak_auto": "akimbo-auto"}
# Blast damage for the grenade (combat.toml), which the weapon table lists as 0.
GRENADE_DAMAGE = 110
# TS 2.1: the grenade's blast (combat21.toml), the knife slash (combat 35, seal 15) and the katana's
# standing swing (trunc(70 x 0.85) = 59), which 2.1's blade code hard-codes rather than reading the
# table (the-specialistsmod-rs crates/ts21/src/shared/melee.rs).
GRENADE_DAMAGE_21 = 100
BLADE_DAMAGE_21 = {25: 35, 35: 15, 34: 59}
STOCK_DAMAGE_21 = 20

HEADER_30 = [
    "// TS 3.0 weapon stats, generated by scripts/gen-weapons.py from the Rust port's decoded",
    "// tables (the-specialistsmod-rs crates/shared/data/weapons.toml, from ts_i386.so).",
    "// Kung fu (weapon 0) is left out. Damage is per bullet; shotguns fire `pellets` per shot.",
    "// Pellet guns are listed as shotguns (TS files the USAS-12 and Sawed-off by HUD category),",
    "// the grenade's damage is its blast, and akimbo-only pairs are flagged.",
]
HEADER_21 = [
    "// TS 2.1 weapon stats, generated by scripts/gen-weapons.py --ts21 from the Rust port's decoded",
    "// tables (the-specialistsmod-rs crates/ts21/data/weapons21.toml and ammo21.toml, from 2.1's mp.dll).",
    "// Kung fu (weapon 0) is left out. Damage is per bullet, the ammo type's base damage times the",
    "// weapon's multiplier; shotguns fire `pellets` per shot. Pellet guns are listed as shotguns, the",
    "// grenade's damage is its blast, a blade's is its slash (the katana's standing swing), and",
    "// akimbo-only pairs are flagged. 2.1 has no Beretta 92F (2), Contender (36) or Akimbo",
    "// Skorpions (37), and 17 is the STEYR-TMP.",
]


def s(x):
    return "'" + x.replace("'", "\\'") + "'"


def arr(xs):
    return "[" + ", ".join(s(x) for x in xs) + "]"


def num(x):
    return str(int(x)) if x == int(x) else repr(round(x, 4))


def damage_30(w):
    return GRENADE_DAMAGE if w["kind"] == "grenade" else w["damage"]


def stock_30(w):
    return w["stock"]


def entry(w, damage, stock):
    melee = w["kind"] in ("grenade", "knife", "katana")
    kind = KIND[w["kind"]]
    if w["pellets"] > 1 and not melee:
        kind = "Shotgun"
    modes = [] if melee else [MODE[m] for m in w["modes"]]
    att = [n for b, n in ATT if w["att_allowed"] & b and not w["att_default"] & b]
    built = [n for b, n in ATT if w["att_default"] & b]
    fields = [
        f"id: {w['id']}",
        f"name: {s(w['name'])}",
        f"kind: {s(kind)}",
        f"slots: {w['slots']}",
        f"cost: {w['cost']}",
        f"clip: {'null' if melee else w['clip']}",
        f"damage: {num(damage)}",
        f"pellets: {w['pellets'] if w['pellets'] > 1 and not melee else 'null'}",
        f"rate: {num(w['rate'])}",
        f"reload: {num(w['reload'])}",
        f"stock: {stock}",
        f"modes: {arr(modes)}",
        f"attachments: {arr(att)}",
        f"builtIn: {arr(built)}",
        f"pairId: {w['akimbo'] if w['akimbo'] >= 0 else 'null'}",
        f"singleId: {w['single'] if w['kind'] == 'akimbo' and w['single'] >= 0 else 'null'}",
        f"akimboOnly: {'true' if w['kind'] == 'akimbo_only' else 'false'}",
        f"stack: {'true' if w['stack'] else 'false'}",
    ]
    return "  { " + ", ".join(fields) + " },"


def gen_30(weapons_toml):
    table = tomllib.loads(Path(weapons_toml).read_text())["weapon"]
    lines = HEADER_30 + [
        "",
        "export type FireMode = 'auto' | 'semi' | 'burst' | 'pump' | 'akimbo-semi' | 'akimbo-auto'",
        "export type Attachment = 'silencer' | 'laser' | 'flashlight' | 'scope'",
        "",
        "export type Weapon = {",
        "  id: number",
        "  name: string",
        "  kind: 'Pistol' | 'SMG' | 'Rifle' | 'Shotgun' | 'Sniper' | 'Akimbo' | 'Grenade' | 'Blade'",
        "  slots: number",
        "  cost: number",
        "  clip: number | null",
        "  damage: number",
        "  pellets: number | null",
        "  /** Seconds between shots (or swings). */",
        "  rate: number",
        "  reload: number",
        "  /** Gun-butt strike damage on the alternate attack key, 0 if none. */",
        "  stock: number",
        "  modes: FireMode[]",
        "  /** Attachments you can add. */",
        "  attachments: Attachment[]",
        "  /** Attachments the weapon always has. */",
        "  builtIn: Attachment[]",
        "  /** Id of this gun's akimbo pair, bought by taking the gun twice. */",
        "  pairId: number | null",
        "  /** For an akimbo pair: the single gun it is made of (two of them). */",
        "  singleId: number | null",
        "  /** Only sold as a pair. */",
        "  akimboOnly: boolean",
        "  /** Bought by count; each one takes `slots`. */",
        "  stack: boolean",
        "}",
        "",
        "export const weapons: Weapon[] = [",
    ]
    lines += [entry(w, damage_30(w), stock_30(w)) for w in table if w["kind"] != "kungfu"]
    lines += [
        "]",
        "",
        "export const weaponById = new Map(weapons.map((w) => [w.id, w]))",
        "",
        "export const attachmentPrices: Record<Attachment, number> = { silencer: 900, laser: 800, flashlight: 500, scope: 1800 }",
        "",
    ]
    return "weapons.ts", lines


def gen_21(weapons_toml, ammo_toml):
    table = tomllib.loads(Path(weapons_toml).read_text())["weapon"]
    ammo = {a["id"]: a["damage"] for a in tomllib.loads(Path(ammo_toml).read_text())["ammo"]}

    def damage(w):
        if w["kind"] == "grenade":
            return GRENADE_DAMAGE_21
        if w["id"] in BLADE_DAMAGE_21:
            return BLADE_DAMAGE_21[w["id"]]
        return ammo[w["ammo"]] * w["mult"]

    lines = HEADER_21 + [
        "",
        "import type { Weapon } from '@/content/weapons'",
        "",
        "export const weapons21: Weapon[] = [",
    ]
    lines += [entry(w, damage(w), STOCK_DAMAGE_21 if w["stock"] else 0) for w in table if w["kind"] != "kungfu"]
    lines += [
        "]",
        "",
        "export const weaponById21 = new Map(weapons21.map((w) => [w.id, w]))",
        "",
    ]
    return "weapons21.ts", lines


def main():
    args = sys.argv[1:]
    name, lines = gen_21(*args[1:3]) if args[:1] == ["--ts21"] else gen_30(args[0])
    out = Path(__file__).resolve().parent.parent / "src/content" / name
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
